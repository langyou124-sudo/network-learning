1. **自然失业率不等于零失业**。充分就业时仍有摩擦性与结构性失业；说「充分就业就是人人有工作」是错的。
2. **失业率分母是劳动力**。不求职的全职学生、退休人员不计入劳动力，因而不直接抬高失业率；但「灰心工人」退出劳动力后，失业率可能被低估。
